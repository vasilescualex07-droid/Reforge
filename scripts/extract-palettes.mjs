#!/usr/bin/env node
// Reforge palette extractor (ROADMAP v4, A1.1).
//
// Reads every wallpaper in public/wallpapers (static jpg + live mp4 first
// frame) through the bundled ffmpeg sidecar, downsamples to 32x32, and emits
// a deterministic palette map to src/styles/palettes.generated.ts:
//   dominant  — most frequent hue-quantized color (the "accent source")
//   secondary — next most frequent distinct color
//   luminance — 0..1 mean brightness (drives the light/dark decision)
//   saturated — whether the dominant color is vivid vs. muted
//
// Offline, one command, committed output. Files that fail to read are omitted
// and the frontend falls back to its keyword heuristic for those ids.

import { execFileSync, spawnSync } from "node:child_process";
import { readdirSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const WP_DIR = join(ROOT, "public", "wallpapers");
const OUT = join(ROOT, "src", "styles", "palettes.generated.ts");

const FFMpeg = [
  join(ROOT, "src-tauri", "resources", "bin", "ffmpeg.exe"),
  "ffmpeg",
].find((p) => existsSync(p));

if (!FFMpeg) {
  console.error("ffmpeg sidecar not found — run once with the desktop build or set ffmpeg on PATH.");
  process.exit(1);
}

const SIZE = 32;

function hex(c) {
  return `#${c.map((v) => (v & 0xff).toString(16).padStart(2, "0")).join("")}`;
}

function analyze(buffer) {
  const pixels = buffer.length / 3;
  if (pixels === 0) return null;

  const buckets = new Map(); // key = r,g,b quantized to 5 bits
  let lumSum = 0;
  for (let i = 0; i < buffer.length; i += 3) {
    const r = buffer[i], g = buffer[i + 1], b = buffer[i + 2];
    lumSum += 0.299 * r + 0.587 * g + 0.114 * b;
    const key = (r >> 3) * 1024 + (g >> 3) * 32 + (b >> 3);
    buckets.set(key, (buckets.get(key) ?? 0) + 1);
  }

  const ranked = [...buckets.entries()].sort((a, b) => b[1] - a[1]);
  const [dk, dc] = ranked[0] ?? [0, 0];
  const dr = ((dk / 1024) | 0) << 3, dg = (((dk / 32) | 0) % 32) << 3, db = (dk % 32) << 3;
  const dominant = [dr, dg, db];

  let secondary = dominant;
  for (const [k] of ranked) {
    const r = ((k / 1024) | 0) << 3, g = (((k / 32) | 0) % 32) << 3, b = (k % 32) << 3;
    const dist = Math.abs(r - dr) + Math.abs(g - dg) + Math.abs(b - db);
    if (dist > 96) { secondary = [r, g, b]; break; }
  }

  const luminance = Math.round((lumSum / pixels / 255) * 1000) / 1000;
  const spread = Math.max(...dominant) - Math.min(...dominant);
  return { dominant: hex(dominant), secondary: hex(secondary), luminance, saturated: spread > 40 };
}

function frame(file) {
  // 32x32 first frame as raw RGB24. Works for stills and video alike.
  const res = spawnSync(
    FFMpeg,
    ["-loglevel", "error", "-i", file, "-vf", `scale=${SIZE}:${SIZE}:flags=area`, "-frames:v", "1", "-f", "rawvideo", "-pix_fmt", "rgb24", "-y", "pipe:1"],
    { maxBuffer: 1024 * 1024 }
  );
  if (res.status !== 0) return null;
  return analyze(res.stdout);
}

const palettes = {};
let ok = 0, failed = 0;

for (const kind of ["static", "live"]) {
  const dir = join(WP_DIR, kind);
  if (!existsSync(dir)) continue;
  for (const f of readdirSync(dir)) {
    // key by kind+stem so the same filename in both bundles (abstract-waves,
    // purple-nebula) keeps its own palette.
    const stem = f.replace(/\.(jpg|jpeg|png|mp4|webm|gif)$/i, "");
    const p = frame(join(dir, f));
    if (p) { palettes[`${kind}/${stem}`] = p; ok++; }
    else { failed++; console.warn(`  ! no palette for ${kind}/${f}`); }
  }
}

const lines = [
  "// AUTO-GENERATED by scripts/extract-palettes.mjs — do not edit by hand.",
  "// Real color data for every bundled wallpaper (ROADMAP v4 A1.1).",
  "export interface WallpaperPalette {",
  "  dominant: string;",
  "  secondary: string;",
  "  luminance: number;",
  "  saturated: boolean;",
  "}",
  "",
  `export const WALLPAPER_PALETTES: Record<string, WallpaperPalette> = {`,
];
for (const [id, p] of Object.entries(palettes).sort(([a], [b]) => a.localeCompare(b))) {
  lines.push(`  ${JSON.stringify(id)}: { dominant: ${JSON.stringify(p.dominant)}, secondary: ${JSON.stringify(p.secondary)}, luminance: ${p.luminance}, saturated: ${p.saturated} },`);
}
lines.push("};");
lines.push(`export const PALETTE_COUNT = ${Object.keys(palettes).length};`);
writeFileSync(OUT, lines.join("\n") + "\n");

console.log(`palettes: ${ok} extracted, ${failed} failed → ${OUT}`);
